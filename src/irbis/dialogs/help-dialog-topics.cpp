#include "irbis/dialogs/help-dialog.h"

#include <QStringList>

namespace {
QString heading(const QString& text) {
    return QStringLiteral("<h3>%1</h3>").arg(text);
}

QString para(const QString& text) {
    return QStringLiteral("<p>%1</p>").arg(text);
}

QString bullets(const QStringList& items) {
    QString html = QStringLiteral("<ul>");
    for (const QString& item : items)
        html += QStringLiteral("<li>%1</li>").arg(item);
    html += QStringLiteral("</ul>");
    return html;
}

QString html_body(const QStringList& parts) {
    return QStringLiteral("<style>"
                          "p { text-align: justify; text-indent: 1.2em; margin: 0 0 8px 0; }"
                          "h3 { font-size: 11pt; margin: 14px 0 6px 0; }"
                          "ul { margin: 0 0 10px 1.4em; padding: 0; }"
                          "li { margin: 0 0 6px 0; text-align: justify; }"
                          "</style>") +
           parts.join(QString());
}

QString join_tr(const QString& a, const QString& b) {
    return a + QLatin1Char(' ') + b;
}
}

